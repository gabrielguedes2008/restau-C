import { JSDOM } from 'jsdom';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const html = await readFile('dist/index.html', 'utf8');
const code = await readFile('dist/app.js', 'utf8');
const dom = new JSDOM(html, { runScripts: 'outside-only', url: 'http://127.0.0.1:4173' });
const { window } = dom;
window.matchMedia = () => ({ addEventListener() {} });
window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new window.Event('close')); };
window.eval(code);
const document = window.document;
const click = selector => document.querySelector(selector).click();
click('.menu-toggle');
assert.equal(document.querySelector('.menu-toggle').getAttribute('aria-expanded'), 'true');
document.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape' }));
assert.equal(document.querySelector('.menu-toggle').getAttribute('aria-expanded'), 'false');
click('[data-menu="parrilla"]');
assert.equal(document.querySelector('#menu-dialog').open, true);
assert.equal(document.querySelectorAll('.dish').length, 2);
click('[data-filter="all"]');
assert.equal(document.querySelectorAll('.dish').length, 6);
click('.menu-reserve');
assert.equal(document.querySelector('#menu-dialog').open, false);
assert.equal(document.querySelector('#reserve-dialog').open, true);
const form = document.querySelector('#reserve-form');
form.elements.name.value = 'Visitante Teste';
form.elements.date.value = '2099-12-01';
form.elements.time.value = '19:30';
form.elements.notes.value = '<script>teste</script>';
form.dispatchEvent(new window.Event('submit', { cancelable: true }));
assert.equal(document.querySelector('#reserve-result').hidden, false);
assert.ok(document.querySelector('#reserve-summary').textContent.includes('Visitante Teste'));
assert.ok(document.querySelector('#reserve-summary').textContent.includes('Solicitação não enviada'));
assert.equal(document.querySelector('#reserve-summary script'), null);
click('#edit-reservation');
assert.equal(form.hidden, false);
form.elements.date.value = '2000-01-01';
form.dispatchEvent(new window.Event('submit', { cancelable: true }));
assert.equal(form.hidden, false);
assert.ok(form.elements.date.validationMessage);
click('[data-location]');
assert.equal(document.querySelector('#location-message').hidden, false);
console.log('Menu mobile, Escape, filtros, transição entre modais, solicitação, edição, data passada e conteúdo seguro: OK.');
window.close();
